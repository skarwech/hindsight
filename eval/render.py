def _table(t: dict) -> str:
    """A result table; numeric columns get an inline bar scaled to the column max (CSS only)."""
    e = html.escape
    nums = [i for i in range(len(t["cols"])) if t["rows"] and all(isinstance(r[i], (int, float)) for r in t["rows"])]
    top = {i: max((abs(r[i]) for r in t["rows"]), default=0) or 1 for i in nums}
    cell = lambda i, v: (f'<td class=m><span class=bar style="width:{60 * abs(v) / top[i]:.0f}px"></span>{v:,}</td>'
                         if i in nums else f"<td>{e(str(v))}</td>")
    head = "".join(f"<th>{e(c)}</th>" for c in t["cols"])
    body = "".join("<tr>" + "".join(cell(i, v) for i, v in enumerate(r)) + "</tr>" for r in t["rows"])
    return f'<h2>{e(t["title"])}</h2><table><tr>{head}</tr>{body}</table>'


def page(docs: dict) -> str:
    e = html.escape
    tiles = "".join(f'<div class="tile {verdict(docs.get(f))}"><b>{f}</b> <span class="pill {verdict(docs.get(f))}">'
                    f'{verdict(docs.get(f))}</span><small>{e(cond)}</small><small>gate {gate}</small></div>'
                    for f, cond, gate in PLAN)
    body = [f"<h1>Hindsight — validation dashboard</h1><p class=sub>Rendered from <code>docs/validation/*.json</code>, "
            f"which the check scripts write. Plan section 12.</p><div class=grid>{tiles}</div>"]
    for f, d in reversed(docs.items()):                 # latest step first
        n = {s: sum(c["status"] == s for c in d["checks"]) for s in ("pass", "fail", "info")}
        rows = "".join(
            f'<tr><td><span class="pill {e(c["status"])}">{e(c["status"])}</span></td><td class=id>{e(c["id"])}</td>'
            f'<td>{e(c["name"])}<details><summary>evidence</summary><pre>{e(c["evidence"]) or "—"}</pre></details></td>'
            f'<td class=k>{e(c["kind"])}</td><td class=m>{e(c["expect"])}</td><td class=m>{e(c["got"])}</td></tr>'
            for c in d["checks"])
        body.append(f'<h2>{e(f)}. {e(d["title"])}</h2><p class="sub counts">gate {e(d["gate"])} · run {e(d["generated"])} · '
                    f'<span class="pill pass">{n["pass"]} pass</span><span class="pill fail">{n["fail"]} fail</span>'
                    f'<span class="pill info">{n["info"]} recorded</span></p>'
                    f'<table><tr><th>Status</th><th>Check</th><th>What</th><th class=k>Kind</th><th>Expected</th><th>Measured</th></tr>{rows}</table>'
                    f'<h2>Findings</h2><ul class=f>' + "".join(f"<li>{e(x)}</li>" for x in d["findings"]) + "</ul>"
                    + "".join(_table(t) for t in d.get("tables", [])))
    return (f"<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
            f"<title>Hindsight validation</title><style>{CSS}</style></head><body><main>{''.join(body)}</main></body></html>")


