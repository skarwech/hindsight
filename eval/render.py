def load() -> dict:
    key = lambda p: (int(re.match(r"f(\d+)", p.stem)[1]), p.stem)     # f4 < f4s < f5
    paths = sorted((p for p in (ROOT / "docs/validation").glob("f*.json") if re.fullmatch(r"f\d+s?", p.stem)), key=key)
    return {p.stem.upper(): json.loads(p.read_text(encoding="utf-8")) for p in paths}


def verdict(doc: dict | None) -> str:
    if not doc or not doc["checks"]:
        return "todo"
    return "fail" if any(c["status"] == "fail" for c in doc["checks"]) else "pass"


def markdown(docs: dict) -> str:
    out = ["# Validation dashboard", "", "Generated by `eval/render.py` from `docs/validation/*.json`. Do not edit.", "",
           "| Feature | Pass condition | Gate | Status |", "|---|---|---|---|"]
    out += [f"| {f} | {cond} | {gate} | {verdict(docs.get(f))} |" for f, cond, gate in PLAN]
    for f, d in docs.items():
        out += ["", f"## {f}. {d['title']} (gate {d['gate']}, run {d['generated']})", "",
                "| Check | Kind | Expected | Measured | Status |", "|---|---|---|---|---|"]
        out += [f"| {c['id']} {c['name']} | {c['kind']} | {c['expect']} | {c['got']} | {c['status']} |" for c in d["checks"]]
        out += ["", "Findings:", ""] + [f"- {x}" for x in d["findings"]]
    return "\n".join(out) + "\n"


